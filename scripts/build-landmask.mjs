// Regenerates src/gl/landmask.js: a 256x128 equirectangular land/ocean bitmask
// used by the hero globe. Only needed if you want a different resolution.
//
//   npm i --no-save world-atlas topojson-client
//   node scripts/build-landmask.mjs
//
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const W = 256;
const H = 128;

const world = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(world, world.objects.land);
const geoms = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry];

// Flatten to a list of polygons, each a list of rings, with a bounding box.
const polys = [];
for (const g of geoms) {
  const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const rings of list) {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of rings[0]) {
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
    polys.push({ rings, minX, minY, maxX, maxY });
  }
}

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  for (const p of polys) {
    if (lon < p.minX || lon > p.maxX || lat < p.minY || lat > p.maxY) continue;
    let inside = false;
    for (const ring of p.rings) if (inRing(ring, lon, lat)) inside = !inside;
    if (inside) return true;
  }
  return false;
}

const bytes = new Uint8Array((W * H) / 8);
let count = 0;
for (let j = 0; j < H; j++) {
  const lat = 90 - ((j + 0.5) * 180) / H;
  for (let i = 0; i < W; i++) {
    const lon = -180 + ((i + 0.5) * 360) / W;
    if (isLand(lon, lat)) {
      const idx = j * W + i;
      bytes[idx >> 3] |= 0x80 >> (idx & 7);
      count++;
    }
  }
}

const b64 = Buffer.from(bytes).toString('base64');
const out = `// Generated by scripts/build-landmask.mjs from Natural Earth 110m land (public domain).
// ${W}x${H} equirectangular bitmask, row 0 = 90N, column 0 = 180W, MSB first.
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_B64 =
  '${b64}';
`;
writeFileSync(new URL('../src/gl/landmask.js', import.meta.url), out);
console.log(`land cells: ${count}/${W * H} (${((100 * count) / (W * H)).toFixed(1)}%), base64 ${b64.length} chars`);

// ASCII preview
let preview = '';
for (let j = 0; j < H; j += 4) {
  for (let i = 0; i < W; i += 2) {
    const idx = j * W + i;
    preview += bytes[idx >> 3] & (0x80 >> (idx & 7)) ? '#' : '.';
  }
  preview += '\n';
}
console.log(preview);
